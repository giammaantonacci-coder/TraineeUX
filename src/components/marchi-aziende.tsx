/**
 * Le lettere, per chi non ha un marchio qui dentro.
 *
 * Scelte a mano e non ricavate dall'iniziale: Satispay e Shopify comincerebbero
 * uguali, e due targhette identiche sono il contrario di quello che servono a
 * fare.
 */
const MONOGRAMMI: Record<string, string> = {
  nngroup: "NN/g",
  satispay: "Sa",
  "bending-spoons": "BS",
  "gov-uk": "GOV.UK",
};

export function MarchioAzienda({ id, name }: { id: string; name: string }) {
  const tracciato = TRACCIATI[id];
  const monogramma = MONOGRAMMI[id] ?? name.slice(0, 1).toUpperCase();

  return (
    <span
      aria-hidden="true"
      className="flex h-11 w-11 shrink-0 items-center justify-center rounded-2xl bg-black/[0.04]"
    >
      {tracciato ? (
        <svg
          viewBox="0 0 24 24"
          fill="currentColor"
          className="h-[21px] w-[21px]"
          aria-hidden="true"
          focusable="false"
        >
          <path d={tracciato} />
        </svg>
      ) : (
        /* La misura scende con la lunghezza: "GOV.UK" a corpo pieno toccherebbe
           i bordi, e sei lettere strette non si leggono meglio di due larghe. */
        <span
          className={`font-extrabold tracking-tight ${
            monogramma.length >= 5
              ? "text-[10px]"
              : monogramma.length >= 3
                ? "text-[13px]"
                : "text-[17px]"
          }`}
        >
          {monogramma}
        </span>
      )}
    </span>
  );
}
